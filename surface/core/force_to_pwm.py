_thruster_data = {
    't-100': (T100thrust, T100pwm),
    't-200': (np.sort(T200thrust), T200pwm),
}


def convert_motor_powers_to_pwms(motor_powers):
    pwms = []
    for thrust, cfg in zip(motor_powers, thruster_config):
        thrust_arr, pwm_arr = _thruster_data[cfg['model']]
        min_thrust = 0.1
        if _thruster_data[cfg['model']] == "t-200":
            min_thrust = 0.3
        pwm_lookup = 3000 - pwm_arr if cfg.get('direction', 1) * cfg.get('handing', 1) < 0 else pwm_arr
        pwms.append(1500 if abs(thrust) < min_thrust else int(np.interp(thrust, thrust_arr, pwm_lookup)))
    return pwms
